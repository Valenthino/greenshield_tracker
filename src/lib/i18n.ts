export function translate(lang: Lang, text: string, values: Record<string, string | number> = {}) {
  let out = lang === "fr" ? (fr[text] ?? text) : text;
  for (const [key, value] of Object.entries(values)) out = out.replaceAll(`{${key}}`, String(value));
  return out;
}

